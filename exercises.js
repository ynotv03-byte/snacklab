const normalize = value => String(value).toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g,'').trim();
export function findExercises({ query = '', group = '', equipment = '' } = {}) {
  const words = normalize(query).split(/\s+/).filter(Boolean);
  return exercises.filter(item => (!group || item.group === group) && (!equipment || item.equipment === equipment) &&
    words.every(word => normalize([item.name,item.group,item.equipment,item.aliases].join(' ')).includes(word)));
}
